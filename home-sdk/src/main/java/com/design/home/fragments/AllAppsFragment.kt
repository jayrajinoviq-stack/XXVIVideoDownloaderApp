package com.design.home.fragments

import android.annotation.SuppressLint
import android.content.Context
import android.util.AttributeSet
import android.view.MotionEvent
import android.view.inputmethod.EditorInfo
import androidx.recyclerview.widget.RecyclerView
import androidx.recyclerview.widget.RecyclerView.OnScrollListener
import androidx.recyclerview.widget.SimpleItemAnimator
import com.design.commons.extensions.beGone
import com.design.commons.extensions.beVisibleIf
import com.design.commons.extensions.getProperPrimaryColor
import com.design.commons.extensions.getProperTextColor
import com.design.commons.extensions.hideKeyboard
import com.design.commons.extensions.normalizeString
import com.design.commons.views.MyGridLayoutManager
import com.design.home.activities.LauncherHomeActivity
import com.design.home.adapters.LaunchersAdapter
import com.design.home.databinding.AllAppsFragmentBinding
import com.design.home.extensions.config
import com.design.home.extensions.getDrawableForPackageName
import com.design.home.extensions.launchApp
